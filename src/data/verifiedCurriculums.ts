export function findVerifiedCurriculum(certName: string): VerifiedCurriculumSpec | undefined {
  const exact = VERIFIED_CURRICULUMS[certName];
  if (exact) return exact;

  const fullNorm = (s: string) => s.replace(/[\s·\-_/()[\]]+/g, '').toLowerCase();
  const baseNorm = (s: string) => s.replace(/\s*\(.*?\)/g, '').replace(/[\s·\-_/]+/g, '').toLowerCase();

  const targetFull = fullNorm(certName);
  const byFull = Object.entries(VERIFIED_CURRICULUMS).find(
    ([key]) => fullNorm(key) === targetFull
  );
  if (byFull) return byFull[1];

  // Only strip parentheses when input itself does not contain a differentiating parenthetical qualifier
  if (!/\([^)]+\)/.test(certName)) {
    const targetBase = baseNorm(certName);
    const byBase = Object.entries(VERIFIED_CURRICULUMS).find(
      ([key]) => baseNorm(key) === targetBase
    );
    return byBase?.[1];
  }

  return undefined;
}
